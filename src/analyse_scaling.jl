# Table and numbers for the scaling study (Supplement S12). Reads chains_scaling.csv written by
# run_scaling.jl, averages over starts and writes summary_scaling.csv, table_scaling.tex and
# scaling_numbers.tex; copies the table into docs/ddcrp-paper/tables/ unless --test.
#
#   julia --project=. src/analyse_scaling.jl [--test]

using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using DataFrames, CSV, Statistics, Printf

const IS_TEST = "--test" in ARGS
const ROOT = joinpath(@__DIR__, "..", "results", IS_TEST ? "scaling_test" : "scaling")
const PAPER = joinpath(@__DIR__, "..", "docs", "ddcrp-paper")

chains = CSV.read(joinpath(ROOT, "chains_scaling.csv"), DataFrame)
S = combine(groupby(chains, [:n, :s, :label, :sampler]; sort = false),
            :n_eff_links => first => :n_eff_links, :n_iter => first => :n_iter,
            :sec_per_1k => mean => :sec_per_1k, :total_time => mean => :total_time,
            :mean_K => mean => :mean_K, :mean_moving_set => mean => :mean_moving_set,
            :ess_K => mean => :ess_K, :ess_K_per_1k => mean => :ess_K_per_1k,
            :ess_K_per_sec => mean => :ess_K_per_sec, :mean_ari => mean => :mean_ari,
            :acc_birth => mean => :acc_birth, :mean_K => (x -> maximum(x) - minimum(x)) => :range_K)
CSV.write(joinpath(ROOT, "summary_scaling.csv"), S)

fmt(x, d) = isfinite(x) ? Printf.format(Printf.Format("%.$(d)f"), x) : "--"
fmts(s) = replace(replace(fmt(s, 3), r"0+$" => ""), r"\.$" => "")
const ORDER = ["collapsed", "rj", "aux_mh", "aux_gibbs"]
const NAME = Dict("collapsed" => "Collapsed", "rj" => "RJ, MM, UL", "aux_mh" => "RJ pool, MM, PL, \$m{=}1\$",
                  "aux_gibbs" => "Aux. Gibbs, MM, \$m{=}1\$")

# Grid points in the order of run_scaling.jl: n at the paper's s, then s at n = 600
points = unique(collect(zip(S.n, S.s)))
sort!(points, by = p -> (p[2] == 0.5 ? 0 : 1, p[2] == 0.5 ? p[1] : 0, p[2]))

open(joinpath(ROOT, "table_scaling.tex"), "w") do io
    println(io, "% Generated by analyse_scaling.jl from chains_scaling.csv; means over two starts.")
    println(io, "\\begin{tabular}{rrr l rrrrr}\n\\toprule")
    println(io, "\$n\$ & \$s\$ & cand. & Sampler & s/1k & \$\\bar K\$ & \$|M|\$ & ESS\$(K)\$/1k & ESS\$(K)\$/s \\\\\n\\midrule")
    for (pi, (n, s)) in enumerate(points)
        pi > 1 && println(io, "\\addlinespace")
        d = S[(S.n .== n) .& (S.s .== s), :]
        for (ri, smp) in enumerate(ORDER)
            r = d[d.sampler .== smp, :]
            nrow(r) == 1 || continue
            r = r[1, :]
            lead = ri == 1 ? "$n & $(fmts(s)) & $(fmt(r.n_eff_links, 1))" : " & & "
            flag = r.range_K > 1 ? "\$^\\dagger\$" : ""   # the two starts disagree on K: not converged
            println(io, "$lead & $(NAME[smp])$flag & $(fmt(r.sec_per_1k, 2)) & $(fmt(r.mean_K, 2)) & " *
                        "$(fmt(r.mean_moving_set, 1)) & $(fmt(r.ess_K_per_1k, 1)) & $(fmt(r.ess_K_per_sec, 2)) \\\\")
        end
    end
    println(io, "\\bottomrule\n\\end{tabular}")
end

# Headline numbers: Gibbs/RJ pool ratio of ESS(K)/s and of s/1k at each grid point, and the
# growth of s/1k with n for each sampler at the paper's s
macros = Pair{String,String}[]
key(n, s) = "N$(n)S" * replace(fmts(s), "." => "p")
for (n, s) in points
    d = S[(S.n .== n) .& (S.s .== s), :]
    g = d[d.sampler .== "aux_gibbs", :]; p = d[d.sampler .== "aux_mh", :]
    (nrow(g) == 1 && nrow(p) == 1) || continue
    push!(macros, "sc$(key(n, s))GibbsRJ" => fmt(g.ess_K_per_sec[1] / p.ess_K_per_sec[1], 2))
    push!(macros, "sc$(key(n, s))CostRatio" => fmt(g.sec_per_1k[1] / p.sec_per_1k[1], 1))
    push!(macros, "sc$(key(n, s))Cand" => fmt(d.n_eff_links[1], 1))
end
base = S[(S.s .== 0.5), :]
const MKEY = Dict("collapsed" => "Collapsed", "rj" => "RJ", "aux_mh" => "Pool", "aux_gibbs" => "Gibbs")
for smp in ORDER
    d = sort(base[base.sampler .== smp, :], :n)
    nrow(d) >= 2 || continue
    push!(macros, "sc$(MKEY[smp])Growth" => fmt(d.sec_per_1k[end] / d.sec_per_1k[1], 1))
    push!(macros, "sc$(MKEY[smp])NRatio" => fmt(d.n[end] / d.n[1], 0))
end
open(joinpath(ROOT, "scaling_numbers.tex"), "w") do io
    println(io, "% Generated by analyse_scaling.jl")
    for (k, v) in macros
        println(io, "\\newcommand{\\$k}{$v}")
    end
end

println(read(joinpath(ROOT, "table_scaling.tex"), String))
if IS_TEST
    println("--test: assets left in $ROOT (docs/ddcrp-paper/ untouched).")
elseif isdir(PAPER)
    cp(joinpath(ROOT, "table_scaling.tex"), joinpath(PAPER, "tables", "table_scaling.tex"); force = true)
    println("Table copied to $PAPER/tables/")
end
