# Table, numbers and figure for the replicated simulated data sets (Supplement S13). Reads
# chains_replicates.csv written by run_replicates.jl, averages the two starts of each data set,
# and reports over data sets the distribution of ESS(K)/s of each sampler, of its ratio to the
# best RJ pool configuration, and how often each sampler is the most efficient. Writes
# summary_replicates.csv, table_replicates.tex, replicates_numbers.tex and replicates_ess.png;
# copies the table and figure into docs/ddcrp-paper/ unless --test.
#
#   julia --project=. src/analyse_replicates.jl [--test]

using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using DataFrames, CSV, Statistics, Printf, StatsPlots, Random

ENV["GKSwstype"] = "nul"   # headless GR

const IS_TEST = "--test" in ARGS
const ROOT = joinpath(@__DIR__, "..", "results", IS_TEST ? "replicates_test" : "replicates")
const PAPER = joinpath(@__DIR__, "..", "docs", "ddcrp-paper")

chains = CSV.read(joinpath(ROOT, "chains_replicates.csv"), DataFrame)

# One row per data set and sampler: means over the two starts, and whether the starts agree on K
D = combine(groupby(chains, [:study, :scenario, :rep, :label, :role, :sampler]; sort = false),
            :sec_per_1k => mean => :sec_per_1k, :mean_K => mean => :mean_K,
            :mean_K => (x -> maximum(x) - minimum(x)) => :range_K,
            :ess_K => mean => :ess_K, :ess_K_per_1k => mean => :ess_K_per_1k,
            :ess_K_per_sec => mean => :ess_K_per_sec, :mean_ari => mean => :mean_ari)
# Ratio to the best RJ pool configuration of the same data set, and the most efficient sampler
pool = Dict((r.study, r.scenario, r.rep) => r.ess_K_per_sec for r in eachrow(D) if occursin("pool_best", r.role))
D.ratio_to_pool = [r.ess_K_per_sec / pool[(r.study, r.scenario, r.rep)] for r in eachrow(D)]
best = Dict(k => g.label[argmax(g.ess_K_per_sec)] for (k, g) in pairs(groupby(D, [:study, :scenario, :rep])))
D.is_best = [best[(study = r.study, scenario = r.scenario, rep = r.rep)] == r.label for r in eachrow(D)]

q(x, p) = quantile(x, p)
S = combine(groupby(D, [:study, :scenario, :label, :role, :sampler]; sort = false),
            nrow => :n_rep, :range_K => (x -> count(>(1), x)) => :n_disagree,
            :sec_per_1k => median => :sec_per_1k,
            :ess_K_per_sec => median => :ess_med, :ess_K_per_sec => (x -> q(x, 0.1)) => :ess_q10,
            :ess_K_per_sec => (x -> q(x, 0.9)) => :ess_q90,
            :ratio_to_pool => median => :ratio_med, :ratio_to_pool => (x -> q(x, 0.1)) => :ratio_q10,
            :ratio_to_pool => (x -> q(x, 0.9)) => :ratio_q90,
            :ratio_to_pool => (x -> mean(x .> 1)) => :frac_beats_pool,
            :is_best => mean => :frac_best)
CSV.write(joinpath(ROOT, "summary_replicates.csv"), S)

# Table

fmt(x, d) = isfinite(x) ? Printf.format(Printf.Format("%.$(d)f"), x) : "--"
const TEXLABEL = [r"^Gibbs" => "Aux. Gibbs", " q:mm" => ", MM", " q:prior" => ", prior", " link:metropolised" => ", ML",
                  " link:prior" => ", PL", " link:uniform" => ", UL", r" m=(\d+)" => s", $m{=}\1$"]
texlabel(l) = foldl(replace, TEXLABEL; init = l)
const PANEL = Dict(("poisson", "overlapping") => ("Poisson", "Poisson"),
                   ("skewnormal", "overlapping") => ("Skew-normal, overlapping", "SkewOverlapping"),
                   ("skewnormal", "separated") => ("Skew-normal, separated", "SkewSeparated"))
const ROLE_ORDER = ["collapsed", "rj_ul", "pool_m1", "pool_best", "gibbs_best"]
rolerank(role) = minimum(findfirst(==(r), ROLE_ORDER) for r in split(role, "+"))
panels = sort(unique(collect(zip(S.study, S.scenario))), by = p -> (p[1] != "poisson", p[2]))

open(joinpath(ROOT, "table_replicates.tex"), "w") do io
    n_rep = maximum(S.n_rep)
    println(io, "% Generated by analyse_replicates.jl from chains_replicates.csv: over $n_rep data sets per scenario,")
    println(io, "% medians and 10--90% ranges of ESS(K)/s (means over two starts) and of its ratio to the best RJ pool")
    println(io, "% configuration, and the fraction of data sets on which each sampler is the most efficient.")
    println(io, "\\begin{tabular}{l l rr rr r}\n\\toprule")
    println(io, " & & \\multicolumn{2}{c}{ESS\$(K)\$/s} & \\multicolumn{2}{c}{Ratio to RJ pool} & \\\\")
    println(io, "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}")
    println(io, "Data & Sampler & median & 10--90\\% & median & 10--90\\% & Best (\\%) \\\\\n\\midrule")
    for (pi, (st, sc)) in enumerate(panels)
        d = sort(S[(S.study .== st) .& (S.scenario .== sc), :], :role, by = rolerank)
        pi > 1 && println(io, "\\addlinespace")
        for (ri, r) in enumerate(eachrow(d))
            println(io, (ri == 1 ? PANEL[(st, sc)][1] : "") * " & $(texlabel(r.label)) & $(fmt(r.ess_med, 2)) & " *
                        "$(fmt(r.ess_q10, 2))--$(fmt(r.ess_q90, 2)) & $(fmt(r.ratio_med, 2)) & " *
                        "$(fmt(r.ratio_q10, 2))--$(fmt(r.ratio_q90, 2)) & $(fmt(100 * r.frac_best, 0)) \\\\")
        end
    end
    println(io, "\\bottomrule\n\\end{tabular}")
end

# Numbers: per scenario, the Gibbs/RJ pool ratio's median and range, how often Gibbs wins, and
# how often each role is best
macros = Pair{String,String}["rpNRep" => string(maximum(S.n_rep))]
const RKEY = Dict("collapsed" => "Collapsed", "rj_ul" => "RJ", "pool_m1" => "PoolOne", "pool_best" => "Pool", "gibbs_best" => "Gibbs")
for (st, sc) in panels
    d = S[(S.study .== st) .& (S.scenario .== sc), :]
    key = PANEL[(st, sc)][2]
    g = d[occursin.("gibbs_best", d.role), :][1, :]
    append!(macros, ["rp$(key)GibbsRatioMed" => fmt(g.ratio_med, 2), "rp$(key)GibbsRatioLo" => fmt(g.ratio_q10, 2),
                     "rp$(key)GibbsRatioHi" => fmt(g.ratio_q90, 2), "rp$(key)GibbsWins" => fmt(100 * g.frac_beats_pool, 0),
                     "rp$(key)Disagree" => string(maximum(d.n_disagree))])
    for r in eachrow(d), role in split(r.role, "+")
        push!(macros, "rp$(key)$(RKEY[role])Best" => fmt(100 * r.frac_best, 0))
        push!(macros, "rp$(key)$(RKEY[role])Label" => texlabel(r.label))
    end
end
open(joinpath(ROOT, "replicates_numbers.tex"), "w") do io
    println(io, "% Generated by analyse_replicates.jl")
    for (k, v) in macros
        println(io, "\\newcommand{\\$k}{$v}")
    end
end

# Figure: ESS(K)/s of every sampler on every data set, one panel per scenario

const ROLE_COLOUR = Dict("collapsed" => colorant"#0b0b0b", "rj_ul" => colorant"#1baf7a", "pool_m1" => colorant"#eda100",
                         "pool_best" => colorant"#b0233c", "gibbs_best" => colorant"#2a78d6")
plots = map(enumerate(panels)) do (i, (st, sc))
    d = sort(S[(S.study .== st) .& (S.scenario .== sc), :], :role, by = rolerank)
    p = plot(yscale = :log10, title = PANEL[(st, sc)][1], titlefontsize = 12, legend = false,
             ylabel = i == 1 ? "ESS(K) / s" : "", guidefontsize = 11, tickfontsize = 9,
             xticks = (1:nrow(d), texlabel.(d.label)), xrotation = 25, bottom_margin = 12StatsPlots.mm,
             yformatter = y -> string(round(y; sigdigits = 2)), gridalpha = 0.15, framestyle = :axes)
    rng = MersenneTwister(1)
    for (k, r) in enumerate(eachrow(d))
        x = D[(D.study .== st) .& (D.scenario .== sc) .& (D.label .== r.label), :ess_K_per_sec]
        cl = ROLE_COLOUR[first(split(r.role, "+"))]
        scatter!(p, k .+ 0.25 .* (rand(rng, length(x)) .- 0.5), x; color = cl, markersize = 4, markerstrokewidth = 0, alpha = 0.6)
        plot!(p, [k - 0.3, k + 0.3], [r.ess_med, r.ess_med]; color = cl, lw = 3)
    end
    p
end
fig = plot(plots...; layout = (1, length(plots)), size = (380 * length(plots), 420), left_margin = 6StatsPlots.mm)
savefig(fig, joinpath(ROOT, "replicates_ess.png"))

println(read(joinpath(ROOT, "table_replicates.tex"), String))
if IS_TEST
    println("--test: assets left in $ROOT (docs/ddcrp-paper/ untouched).")
elseif isdir(PAPER)
    cp(joinpath(ROOT, "table_replicates.tex"), joinpath(PAPER, "tables", "table_replicates.tex"); force = true)
    cp(joinpath(ROOT, "replicates_ess.png"), joinpath(PAPER, "figures", "replicates_ess.png"); force = true)
    println("Table and figure copied to $PAPER/{tables,figures}/")
end
