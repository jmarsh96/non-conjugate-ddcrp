# Tables for the birth oracle diagnostic (diagnose_births.jl), from diagnose_births_summary.csv:
# the full table by moving-set size (supplement) and a condensed one for the main text. Both are
# copied into docs/ddcrp-paper/tables/ unless --test.
#
#   julia --project=. src/analyse_births.jl [--test]

using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using DataFrames, CSV, Printf

const IS_TEST = "--test" in ARGS
const PAPER = joinpath(@__DIR__, "..", "docs", "ddcrp-paper")
const ROOT = joinpath(@__DIR__, "..", "results", IS_TEST ? "sampler_study_test" : "sampler_study")

fmt(x, d) = isfinite(x) ? Printf.format(Printf.Format("%.$(d)f"), x) : "--"

# The full table by moving-set size, and a condensed one for
# the main text (A* by size, then the overall A*, observed acceptance and their ratio), all in %
const ORACLE_DATA = ["overlapping" => "Skew-normal, overlapping", "separated" => "Skew-normal, separated",
                     "aba" => "Skew-normal, three groups", "k5" => "Skew-normal, five clusters",
                     "faithful" => "Old Faithful"]
const ORACLE_BINS = ["1" => "1", "2-3" => "2--3", "4-10" => "4--10", "11-30" => "11--30", ">30" => "\$>30\$"]
pct(x) = (y = 100x; 0 < y < 0.005 ? "\$<0.01\$" : fmt(y, 2))
diag_file = joinpath(ROOT, "diagnose_births_summary.csv")
isfile(diag_file) || error("run diagnose_births.jl first: no $diag_file")
begin
    dg = CSV.read(diag_file, DataFrame)
    row(sc, bin) = dg[(dg.scenario .== sc) .& (string.(dg.bin) .== bin), :][1, :]
    datasets = filter(p -> first(p) in dg.scenario, ORACLE_DATA)
    open(joinpath(ROOT, "table_births_oracle.tex"), "w") do io
        println(io, "% Generated by analyse_births.jl from diagnose_births_summary.csv: birth acceptance (%)")
        println(io, "% observed vs the bound A* of the exact conditional parameter proposal, weighted by birth probability.")
        println(io, "\\begin{tabular}{ll rrrr}\n\\toprule\nData & \$|M|\$ & Births & Observed & \$A^*\$ & Ratio \\\\\n\\midrule")
        for (di, (sc, name)) in enumerate(datasets)
            di > 1 && println(io, "\\addlinespace")
            for (bi, (bin, binlab)) in enumerate(vcat(ORACLE_BINS, "all" => "All"))
                r = row(sc, bin)
                println(io, (bi == 1 ? name : "") * " & $binlab & $(ismissing(r.n_moves) ? "" : r.n_moves) & " *
                            "$(pct(r.acc_obs)) & $(pct(r.A_star)) & $(fmt(r.ratio, 2)) \\\\")
            end
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end
    open(joinpath(ROOT, "table_births_oracle_main.tex"), "w") do io
        println(io, "% Generated by analyse_births.jl from diagnose_births_summary.csv: A* (%) by moving-set")
        println(io, "% size, then overall A*, observed acceptance (%) and their ratio.")
        println(io, "\\begin{tabular}{l rrrrr rrr}\n\\toprule")
        println(io, " & \\multicolumn{5}{c}{\$A^*\$ by \$|M|\$} & \\multicolumn{3}{c}{Overall} \\\\")
        println(io, "\\cmidrule(lr){2-6}\\cmidrule(lr){7-9}")
        println(io, "Data & " * join(last.(ORACLE_BINS), " & ") * " & \$A^*\$ & Observed & Ratio \\\\\n\\midrule")
        for (sc, name) in datasets
            r = row(sc, "all")
            println(io, "$name & " * join([pct(row(sc, b).A_star) for b in first.(ORACLE_BINS)], " & ") *
                        " & $(pct(r.A_star)) & $(pct(r.acc_obs)) & $(fmt(r.ratio, 2)) \\\\")
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end
end

# Paper copies
files = [joinpath(ROOT, f) for f in ("table_births_oracle.tex", "table_births_oracle_main.tex")]
if IS_TEST
    println("--test: tables left in $ROOT (docs/ddcrp-paper/ untouched).")
elseif !isdir(PAPER)
    println("No paper directory at $PAPER (docs/ is git-ignored): tables left in $ROOT.")
else
    foreach(f -> cp(f, joinpath(PAPER, "tables", basename(f)); force = true), files)
    println("Paper tables copied to $PAPER/tables/")
end
